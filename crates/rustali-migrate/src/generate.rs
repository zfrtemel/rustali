//! Render schema changes as a human-readable `sea-orm-migration` file.
//!
//! The output is deliberately ordinary migration code — the same `Table::create()` /
//! `Table::alter()` a developer would write by hand — so it can be read, edited and
//! reviewed. `migrate:diff` writes it; nothing executes generated strings.

use rustali_orm::schema::{Column, ColumnChange, ColumnType, SchemaChange, Table};

/// Render a full migration module body (the `up`/`down` and `Iden` enums) for `changes`.
#[must_use]
pub fn migration_source(module: &str, changes: &[SchemaChange]) -> String {
    let up = changes.iter().map(up_stmt).collect::<Vec<_>>().join("\n\n");
    let down = changes
        .iter()
        .rev()
        .map(down_stmt)
        .collect::<Vec<_>>()
        .join("\n\n");
    let idens = iden_enums(changes);

    format!(
        "//! Generated by `rustali migrate:diff`. Review before applying; edit freely.\n\
         #![allow(elided_lifetimes_in_paths)]\n\n\
         use rustali::migrate::prelude::*;\n\n\
         #[derive(DeriveMigrationName)]\n\
         pub struct Migration;\n\n\
         #[async_trait::async_trait]\n\
         impl MigrationTrait for Migration {{\n\
         {INDENT}async fn up(&self, manager: &SchemaManager) -> Result<(), DbErr> {{\n{up}\n{INDENT}}}\n\n\
         {INDENT}async fn down(&self, manager: &SchemaManager) -> Result<(), DbErr> {{\n{down}\n{INDENT}}}\n\
         }}\n\n\
         {idens}\n\
         // module: {module}\n",
        INDENT = "    ",
    )
}

fn up_stmt(change: &SchemaChange) -> String {
    match change {
        SchemaChange::CreateTable(table) => create_table(table),
        SchemaChange::DropTable { name } => drop_table(name),
        SchemaChange::AlterTable(diff) => alter_table(&diff.table, &diff.changes, false),
    }
}

fn down_stmt(change: &SchemaChange) -> String {
    match change {
        // The reverse of create is drop and vice versa; alters are inverted per column.
        SchemaChange::CreateTable(table) => drop_table(&table.name),
        SchemaChange::DropTable { name } => {
            format!(
                "        // TODO: recreate `{name}` — its definition was removed from the snapshot.\n        let _ = manager;"
            )
        }
        SchemaChange::AlterTable(diff) => alter_table(&diff.table, &diff.changes, true),
    }
}

fn create_table(table: &Table) -> String {
    let iden = iden(&table.name);
    let cols = table
        .columns
        .iter()
        .map(|c| format!("                    .col({})", column_def(&table.name, c)))
        .collect::<Vec<_>>()
        .join("\n");
    format!(
        "        manager\n\
         {I}.create_table(\n\
         {I}{I}Table::create()\n\
         {I}{I}{I}.table({iden}::Table)\n\
         {I}{I}{I}.if_not_exists()\n\
         {cols}\n\
         {I}{I}{I}.to_owned(),\n\
         {I})\n\
         {I}.await?;",
        I = "            ",
    )
}

fn drop_table(name: &str) -> String {
    let iden = iden(name);
    format!(
        "        manager\n\
         {I}.drop_table(Table::drop().table({iden}::Table).if_exists().to_owned())\n\
         {I}.await?;",
        I = "            ",
    )
}

fn alter_table(table: &str, changes: &[ColumnChange], reverse: bool) -> String {
    let iden = iden(table);
    let mut stmts = Vec::new();
    for change in changes {
        let body = if reverse {
            alter_reverse(table, change)
        } else {
            Some(alter_forward(table, change))
        };
        if let Some(body) = body {
            stmts.push(format!(
                "        manager\n\
                 {I}.alter_table(Table::alter().table({iden}::Table){body}.to_owned())\n\
                 {I}.await?;",
                I = "            ",
            ));
        }
    }
    if stmts.is_empty() {
        "        let _ = manager;".to_owned()
    } else {
        stmts.join("\n")
    }
}

fn alter_forward(table: &str, change: &ColumnChange) -> String {
    match change {
        ColumnChange::AddColumn(col) => format!(".add_column({})", column_def(table, col)),
        ColumnChange::DropColumn { name } => {
            format!(".drop_column({}::{})", iden(table), variant(name))
        }
        ColumnChange::AlterColumn { to, .. } => {
            format!(".modify_column({})", column_def(table, to))
        }
    }
}

fn alter_reverse(table: &str, change: &ColumnChange) -> Option<String> {
    match change {
        ColumnChange::AddColumn(col) => Some(format!(
            ".drop_column({}::{})",
            iden(table),
            variant(&col.name)
        )),
        ColumnChange::DropColumn { .. } => None, // original definition unknown; skip in down
        ColumnChange::AlterColumn { from, .. } => {
            Some(format!(".modify_column({})", column_def(table, from)))
        }
    }
}

/// `ColumnDef::new(Users::Email).string_len(255).not_null()`
fn column_def(table: &str, col: &Column) -> String {
    let mut def = format!("ColumnDef::new({}::{})", iden(table), variant(&col.name));
    def.push_str(&type_call(&col.ty));
    if col.primary_key {
        if col.auto_increment {
            def.push_str(".auto_increment()");
        }
        def.push_str(".primary_key()");
    }
    if col.nullable {
        def.push_str(".null()");
    } else {
        def.push_str(".not_null()");
    }
    if col.unique && !col.primary_key {
        def.push_str(".unique_key()");
    }
    def
}

fn type_call(ty: &ColumnType) -> String {
    match ty {
        ColumnType::SmallInt => ".small_integer()".into(),
        ColumnType::Int => ".integer()".into(),
        ColumnType::BigInt => ".big_integer()".into(),
        ColumnType::Double => ".double()".into(),
        ColumnType::Boolean => ".boolean()".into(),
        ColumnType::Text { max_len: Some(n) } => format!(".string_len({n})"),
        ColumnType::Text { max_len: None } => ".text()".into(),
        ColumnType::Timestamp => ".timestamp_with_time_zone()".into(),
        ColumnType::Date => ".date()".into(),
        ColumnType::Uuid => ".uuid()".into(),
        ColumnType::Json => ".json()".into(),
        ColumnType::Bytes => ".binary()".into(),
        ColumnType::Unknown { rust_type } => {
            format!(".text() /* FIXME: unmapped Rust type `{rust_type}` */")
        }
    }
}

/// Generate the `#[derive(DeriveIden)]` enums for every table touched.
fn iden_enums(changes: &[SchemaChange]) -> String {
    let mut out = Vec::new();
    for change in changes {
        let (table, columns): (&str, Vec<String>) = match change {
            SchemaChange::CreateTable(t) => (
                t.name.as_str(),
                t.columns.iter().map(|c| c.name.clone()).collect(),
            ),
            SchemaChange::DropTable { name } => (name.as_str(), Vec::new()),
            SchemaChange::AlterTable(d) => (
                d.table.as_str(),
                d.changes.iter().map(column_name).collect(),
            ),
        };
        let variants = std::iter::once("Table".to_owned())
            .chain(columns.into_iter().map(|c| variant(&c)))
            .collect::<Vec<_>>();
        // De-duplicate variants, preserving order.
        let mut seen = Vec::new();
        for v in variants {
            if !seen.contains(&v) {
                seen.push(v);
            }
        }
        out.push(format!(
            "#[derive(DeriveIden)]\nenum {} {{\n{}\n}}",
            iden(table),
            seen.iter()
                .map(|v| format!("    {v},"))
                .collect::<Vec<_>>()
                .join("\n"),
        ));
    }
    out.join("\n\n")
}

fn column_name(change: &ColumnChange) -> String {
    match change {
        ColumnChange::AddColumn(c) => c.name.clone(),
        ColumnChange::DropColumn { name } => name.clone(),
        ColumnChange::AlterColumn { to, .. } => to.name.clone(),
    }
}

/// `users` → `Users` (the Iden enum name).
fn iden(table: &str) -> String {
    to_camel(table)
}

/// `created_at` → `CreatedAt` (the Iden variant).
fn variant(column: &str) -> String {
    to_camel(column)
}

fn to_camel(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    let mut upper = true;
    for ch in s.chars() {
        if ch == '_' || ch == '-' {
            upper = true;
        } else if upper {
            out.extend(ch.to_uppercase());
            upper = false;
        } else {
            out.push(ch);
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use rustali_orm::schema::{Column, ColumnType, Table};

    use super::*;

    fn pk() -> Column {
        Column {
            name: "id".into(),
            ty: ColumnType::BigInt,
            nullable: false,
            primary_key: true,
            auto_increment: true,
            unique: false,
        }
    }

    #[test]
    fn create_table_source_is_valid_shaped() {
        let table = Table {
            name: "users".into(),
            columns: vec![
                pk(),
                Column {
                    name: "email".into(),
                    ty: ColumnType::Text { max_len: Some(255) },
                    nullable: false,
                    primary_key: false,
                    auto_increment: false,
                    unique: true,
                },
            ],
        };
        let src = migration_source("m_create_users", &[SchemaChange::CreateTable(table)]);
        assert!(src.contains("impl MigrationTrait for Migration"));
        assert!(src.contains("Table::create()"));
        assert!(
            src.contains("ColumnDef::new(Users::Email).string_len(255).not_null().unique_key()")
        );
        assert!(src.contains(
            "ColumnDef::new(Users::Id).big_integer().auto_increment().primary_key().not_null()"
        ));
        assert!(src.contains("enum Users"));
        assert!(!src.contains("CreatedAt"), "no stray variants");
        // down drops the table
        assert!(src.contains("drop_table(Table::drop().table(Users::Table)"));
    }

    #[test]
    fn camel_case_helper() {
        assert_eq!(to_camel("users"), "Users");
        assert_eq!(to_camel("created_at"), "CreatedAt");
        assert_eq!(to_camel("oauth_tokens"), "OauthTokens");
    }
}
